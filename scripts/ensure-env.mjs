#!/usr/bin/env node
/**
 * Automatically provisions environment files and SQLite database on first run
 * so that a fresh clone starts with `npm install && npm run dev` or `start.bat`
 * with zero manual configuration.
 */

import { randomBytes } from 'node:crypto'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const backendDir = join(root, 'backend')
const frontendDir = join(root, 'frontend')
const envFile = join(backendDir, '.env')
const frontendEnvFile = join(frontendDir, '.env')
const dataDir = join(root, 'data')

if (!existsSync(dataDir)) {
  mkdirSync(dataDir, { recursive: true })
}

if (!existsSync(envFile)) {
  if (process.env.NODE_ENV === 'production') {
    console.error('Refusing to generate backend/.env in production.')
    console.error('Set JWT_ACCESS_SECRET and TOKEN_ENCRYPTION_KEY yourself. See .env.example.')
    process.exit(1)
  }

  const secret = () => randomBytes(32).toString('base64url')

  writeFileSync(
    envFile,
    `# Generated by \`npm run dev\` on first run. Safe to edit.
# Not committed. See .env.example at the repo root for every available option.

NODE_ENV=development

# SQLite needs no database server. Switch to mysql or postgres by setting
# DATABASE_PROVIDER and DATABASE_URL, then running \`npm run db:migrate\`.
DATABASE_PROVIDER=sqlite
DATABASE_URL="file:./dev.db"

APP_PORT=4000
APP_URL="http://localhost:4000"
FRONTEND_URL="http://localhost:5173"

# Randomly generated for this machine. Rotating them invalidates all sessions,
# and rotating TOKEN_ENCRYPTION_KEY makes stored provider tokens unreadable.
JWT_ACCESS_SECRET="${secret()}"
TOKEN_ENCRYPTION_KEY="${secret()}"
`,
  )

  console.log(`Created ${relative(root, envFile)} with generated development secrets.`)
}

if (!existsSync(frontendEnvFile)) {
  writeFileSync(
    frontendEnvFile,
    `# Better Drive Frontend Environment
VITE_API_URL=http://localhost:4000
`,
  )
  console.log(`Created ${relative(root, frontendEnvFile)} with default API URL.`)
}

// Auto-migrate SQLite if database does not exist
const sqliteDbPath = join(backendDir, 'prisma', 'dev.db')
const isSqlite = (process.env.DATABASE_PROVIDER ?? 'sqlite').toLowerCase() === 'sqlite'

if (isSqlite && !existsSync(sqliteDbPath)) {
  console.log('[*] First-time setup: Initializing SQLite database schema...')
  const migrateResult = spawnSync(
    process.execPath,
    [join(backendDir, 'scripts', 'prisma.mjs'), 'migrate', 'deploy'],
    {
      cwd: root,
      stdio: 'inherit',
    },
  )
  if (migrateResult.status !== 0) {
    console.error('[ERROR] Failed to automatically migrate SQLite database.')
    process.exit(migrateResult.status ?? 1)
  }
  console.log('[*] SQLite database initialized and migrated.')
}
